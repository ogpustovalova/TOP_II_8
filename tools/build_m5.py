nb.add(md(r"""### 6. Vanilla RNN: формула, развёртка и размерности

Для одного объекта переход vanilla RNN с нелинейностью $f$ имеет вид

$$h_t = f(W_x x_t + W_h h_{t-1} + b).$$

Минимальная развёртка на три шага:

$$h_1=f(W_x x_1+W_h h_0+b),$$
$$h_2=f(W_x x_2+W_h h_1+b),$$
$$h_3=f(W_x x_3+W_h h_2+b).$$

Блок единичной задержки хранит выход текущего шага ровно до следующего шага:

```text
x_t ------> [W_x] --\
                         (+ b) --> [f] --> h_t --> [z^-1] --+
h_{t-1} --> [W_h] --/                                      |
             ^                                              |
             +---------------- состояние следующего шага ---+
```

На шаге $t+1$ сохранённое значение $h_t$ играет роль предыдущего состояния.
Для $B$ объектов, длины $T$, размера входа $D$ и скрытого размера $H$:

| Объект | Один объект | С batch / последовательностью |
|---|---:|---:|
| $x_t$ | $(D,)$ | $(B,D)$ |
| $h_{t-1}, h_t$ | $(H,)$ | $(B,H)$ |
| $W_x$ (`weight_ih`) | $(H,D)$ | $(H,D)$ |
| $W_h$ (`weight_hh`) | $(H,H)$ | $(H,H)$ |
| $b=b_{ih}+b_{hh}$ | $(H,)$ | broadcast до $(B,H)$ |
| `nn.RNN` output | — | $(B,T,H)$ |
| `nn.RNN` $h_n$ | — | $(1,B,H)$ |

Создайте тензоры с $B=2$, $T=3$, $D=4$, $H=5$ и подтвердите все формы через
`assert`, включая отдельные `x_t`, `h_t`, обе части bias и их сумму. Объясните,
почему $W_h h_{t-1}$ определён и где в схеме находится единичная задержка."""))
